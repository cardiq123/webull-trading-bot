def _pack(rows: tuple[tuple[int, int, int], ...]) -> frozenset[date]:
    return frozenset(date(year, month, day) for year, month, day in rows)


CPI_DATES = _pack(_CPI)
NFP_DATES = _pack(_NFP)
FOMC_DATES = _pack(_FOMC)
EVENT_DATES = CPI_DATES | NFP_DATES | FOMC_DATES


def event_kind(day: date) -> str | None:
    """Which release falls on ``day``, or None. A day can carry more than one name."""
    names = []
    if day in CPI_DATES:
        names.append("CPI")
    if day in NFP_DATES:
        names.append("NFP")
    if day in FOMC_DATES:
        names.append("FOMC")
    if not names:
        return None
    return "+".join(names)
